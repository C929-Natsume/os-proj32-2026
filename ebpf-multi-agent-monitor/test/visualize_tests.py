def main(argv=None):
    ap = argparse.ArgumentParser(description="eBPF Multi-Agent Monitor 测试可视化")
    ap.add_argument("--logs-dir", default="", help="保存测试日志的目录（默认 test/logs）")
    ap.add_argument("--out-dir", default="", help="报告输出目录（默认 test/reports）")
    ap.add_argument("--no-run-unit", action="store_true",
                    help="不实时运行单元测试，仅读取 logs/test_unit.log")
    ap.add_argument("--open", action="store_true", help="生成后自动打开报告")
    args = ap.parse_args(argv)

    out_dir = os.path.abspath(args.out_dir) if args.out_dir else os.path.join(TEST_DIR, "reports")
    logs_dir = _real_log_dir(args.logs_dir)
    os.makedirs(out_dir, exist_ok=True)

    generated_at = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    suites = collect(args)

    images = render_charts(suites)

    env = {
        "kernel": platform.release(),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "matplotlib": matplotlib.__version__ if _MPL else "N/A",
        "cwd": os.getcwd(),
        "unit_bin": os.path.join(TEST_DIR, "test_unit"),
    }

    html_text = build_html(suites, images, env, generated_at, logs_dir)

    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    html_path = os.path.join(out_dir, f"test_visualization_{ts}.html")
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html_text)

    print("=" * 64)
    print("  eBPF Multi-Agent Monitor — 测试可视化报告")
    print("=" * 64)
    for s in suites:
        pc = s.parsed_counts
        if s.status == "RUN":
            badge = s.integrity.get("badge", "?")
            print(f"  [{s.status:>7}] {s.name:<28} PASS={pc['PASS']:<4} "
                  f"FAIL={pc['FAIL']:<4} SKIP={pc['SKIP']:<4} "
                  f"integrity={badge}")
        else:
            print(f"  [NOT_RUN] {s.name:<28} — {s.status_detail[:50]}")
    print("-" * 64)
    print(f"  报告已生成: {html_path}")
    print("=" * 64)

    if args.open:
        import webbrowser
        webbrowser.open(f"file://{html_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
