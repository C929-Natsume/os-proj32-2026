class SuiteResult:
    def __init__(self, key: str, name: str, command: str, needs_root: bool,
                 log_name: str, log_dir: str):
        self.key = key
        self.name = name
        self.command = command
        self.needs_root = needs_root
        self.log_name = log_name
        self.log_dir = log_dir
        self.log_path = os.path.join(log_dir, log_name)

        self.status: str = "NOT_RUN"      # RUN | NOT_RUN
        self.status_detail: str = ""
        self.source: str = ""             # live | log
        self.log_size: int = 0
        self.log_mtime: Optional[str] = None

        self.sections: List[str] = []
        self.cases: List[Dict] = []       # {section,name,status,detail}
        self.summary: Optional[Dict] = None  # {passed,failed,skipped,total}
        self.metrics: Dict = {}           # perf suite
        self.parse_warning: Optional[str] = None

        self.integrity: Dict = {}         # computed by _audit()

    # -- helpers -----------------------------------------------------------
    @property
    def parsed_counts(self) -> Dict:
        c = {"PASS": 0, "FAIL": 0, "SKIP": 0, "UNKNOWN": 0}
        for case in self.cases:
            c[case["status"]] += 1
        return c

    @property
    def parsed_total(self) -> int:
        return len(self.cases)

    def summary_total(self) -> Optional[int]:
        if self.summary:
            return self.summary.get("total")
        return None

    def _audit(self) -> None:
        """Cross-check summary line vs parsed per-case lines."""
        pc = self.parsed_counts
        sum_total = self.summary_total()

        if self.status == "NOT_RUN":
            self.integrity = {
                "badge": "notrun",
                "summary_total": None,
                "parsed_total": 0,
                "consistent": None,
                "note": "套件未运行",
            }
            return

        if self.parse_warning:
            self.integrity = {
                "badge": "unverified",
                "summary_total": sum_total,
                "parsed_total": self.parsed_total,
                "consistent": False,
                "note": self.parse_warning,
            }
            return

        if sum_total is None:
            self.integrity = {
                "badge": "unverified",
                "summary_total": None,
                "parsed_total": self.parsed_total,
                "consistent": None,
                "note": "日志中未找到汇总行，无法交叉校验",
            }
            return

        consistent = (sum_total == self.parsed_total)
        diff = sum_total - self.parsed_total if sum_total is not None else 0
        if consistent:
            badge = "complete"
            note = "汇总行与逐用例解析一致"
        else:
            badge = "partial"
            note = f"汇总行 {sum_total} ≠ 解析用例 {self.parsed_total}（偏差 {diff:+d}；多为静默计数或日志截断）"
        self.integrity = {
            "badge": badge,
            "summary_total": sum_total,
            "parsed_total": self.parsed_total,
            "consistent": consistent,
            "diff": diff,
            "note": note,
        }


