def parse_unit(text: str, result: SuiteResult) -> SuiteResult:
    """Format:
        --- Section ---
          test name ... PASS        (or ... FAIL: msg)
        Results: N passed, M failed, K total
    """
    section = ""
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        sm = re.match(r"^\s*---\s*(.+?)\s*---\s*$", line)
        if sm:
            section = sm.group(1).strip()
            if section not in result.sections:
                result.sections.append(section)
            continue
        cm = re.match(r"^\s*(.+?)\s*\.\.\.\s*(PASS|FAIL)(?:\s*[:：]\s*(.*))?$", line)
        if cm:
            status = cm.group(2)
            result.cases.append(_new_case(section, cm.group(1), status, cm.group(3) or ""))
            continue
    result.summary = _summary_line_match(text)
    return result


def parse_functional(text: str, result: SuiteResult) -> SuiteResult:
    """Format:
        --- Test N: Name ---
          ✓ assertion message
          ✗ failure message
        Results: N passed, M failed, K total
    """
    section = ""
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        sm = re.match(r"^\s*---\s*(.+?)\s*---\s*$", line)
        if sm:
            section = sm.group(1).strip()
            if section not in result.sections:
                result.sections.append(section)
            continue
        pm = re.match(r"^\s*✓\s+(.+)$", line)
        if pm:
            result.cases.append(_new_case(section, pm.group(1), "PASS"))
            continue
        fm = re.match(r"^\s*✗\s+(.+)$", line)
        if fm:
            result.cases.append(_new_case(section, fm.group(1), "FAIL"))
            continue
    result.summary = _summary_line_match(text)
    return result


def parse_integration(text: str, result: SuiteResult) -> SuiteResult:
    """Format:
        ━━━ 1. Section ━━━
          ✓ PASS
          ✗ FAIL: msg
          ∘ SKIP: msg
        SKIP: requires root (sudo)
        Results: P passed, F failed, S skipped
    """
    section = ""
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        sm = re.match(r"^\s*━━━\s*(.+?)\s*━━━\s*$", line)
        if sm:
            section = sm.group(1).strip()
            if section not in result.sections:
                result.sections.append(section)
            continue
        pm = re.match(r"^\s*✓\s*(PASS.*)?$", line)
        if pm:
            result.cases.append(_new_case(section, pm.group(1) or "PASS", "PASS"))
            continue
        fm = re.match(r"^\s*✗\s*FAIL\s*[:：]?\s*(.*)$", line)
        if fm:
            result.cases.append(_new_case(section, fm.group(1) or "FAIL", "FAIL"))
            continue
        km = re.match(r"^\s*∘\s*SKIP\s*[:：]?\s*(.*)$", line)
        if km:
            result.cases.append(_new_case(section, km.group(1) or "SKIP", "SKIP"))
            continue
        sk = re.match(r"^\s*SKIP\s*[:：]?\s*(.*)$", line)
        if sk:
            result.cases.append(_new_case(section, sk.group(1) or "SKIP", "SKIP"))
            continue

    m = re.search(r"Results:\s*(\d+)\s+passed,\s*(\d+)\s+failed,\s*(\d+)\s+skipped",
                  text, re.IGNORECASE)
    if m:
        result.summary = {
            "passed": int(m.group(1)),
            "failed": int(m.group(2)),
            "skipped": int(m.group(3)),
            "total": int(m.group(1)) + int(m.group(2)) + int(m.group(3)),
        }
    return result


def parse_perf(text: str, result: SuiteResult) -> SuiteResult:
    """Format (freeform):
        ━━━ Phase: baseline ━━━
        Phase 1 (基线): 12.34s
        Phase 1 指令数: 1,234,567
        平均开销: 2.10% (指令数)
        管道捕获率: 99.99%
        drop_counter: 0
          ✅ PASS (...)   ❌ FAIL (...)   ⚠️  SKIP (...)
        结果：P 通过, F 失败
    """
    section = ""
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        sm = re.match(r"^\s*━━━\s*(.+?)\s*━━━\s*$", line)
        if sm:
            section = sm.group(1).strip()
            if section not in result.sections:
                result.sections.append(section)
            continue
        # 只统计最终判定断言（消息以 PASS/FAIL/SKIP 开头），排除"xxx 完成"等进度提示
        ok = re.match(r"^\s*✅\s*(PASS\b.*)$", line)
        if ok:
            result.cases.append(_new_case(section, ok.group(1) or "PASS", "PASS"))
            continue
        no = re.match(r"^\s*❌\s*(FAIL\b.*)$", line)
        if no:
            result.cases.append(_new_case(section, no.group(1) or "FAIL", "FAIL"))
            continue
        wa = re.match(r"^\s*⚠️\s*(SKIP\b.*)$", line)
        if wa:
            result.cases.append(_new_case(section, wa.group(1) or "SKIP", "SKIP"))
            continue

    m = re.search(r"结果[:：]?\s*(\d+)\s*通过,\s*(\d+)\s*失败", text)
    if m:
        result.summary = {
            "passed": int(m.group(1)),
            "failed": int(m.group(2)),
            "skipped": 0,
            "total": int(m.group(1)) + int(m.group(2)),
        }

    # ---- metrics extraction -----------------------------------------------
    def grab(pattern: str) -> Optional[str]:
        mm = re.search(pattern, text)
        return mm.group(1).strip() if mm else None

    metrics = result.metrics
    metrics["phase_baseline_s"] = grab(r"Phase\s*1\s*[（(]基线[)）]\s*[:：]?\s*(\S+)")
    metrics["phase_baseline_instr"] = grab(r"Phase\s*1\s*指令数\s*[:：]?\s*([0-9,]+)")
    metrics["phase_fastpath_s"] = grab(r"Phase\s*2\s*[（(]fast-path[)）]\s*[:：]?\s*(\S+)")
    metrics["phase_fastpath_instr"] = grab(r"Phase\s*2\s*指令数\s*[:：]?\s*([0-9,]+)")
    metrics["phase_fullcapture_s"] = grab(r"Phase\s*3\s*[（(]full-capture[)）]\s*[:：]?\s*(\S+)")
    metrics["phase_fullcapture_instr"] = grab(r"Phase\s*3\s*指令数\s*[:：]?\s*([0-9,]+)")
    metrics["overhead_pct"] = grab(r"平均开销\s*[:：]?\s*([0-9.]+)\s*%")
    metrics["capture_rate_pct"] = grab(r"管道捕获率\s*[:：]?\s*([0-9.]+)\s*%")
    metrics["drop_counter"] = grab(r"drop_counter\s*[:：]?\s*(\S+)")
    metrics["overhead_basis"] = grab(r"开销基准\s*[:：]?\s*(.*)")
    return result


def parse_plaintext(text: str, result: SuiteResult) -> SuiteResult:
    """Format:
        [INFO] Test 1: Small payload plaintext capture
        [PASS] Plaintext found (type=prompt, bytes=140)   (详情，不直接计数)
        ...
        Results: 2/3 passed
          PASS  Small payload               (末尾结果清单 = 权威用例，按名归入对应章节)
          FAIL  Large payload
    """
    # ── 第一遍：收集章节及其最有信息量的详情行（到 Results 块为止） ──
    sections = []          # ordered: [{name, detail}]
    current = None
    in_results = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        if in_results:
            continue
        if re.match(r"^\s{2,}(PASS|FAIL)\s+", line) or re.match(r"^Results:", line):
            in_results = True
            continue
        sm = re.match(r"^\[INFO\]\s*Test\s*\d+\s*[:：]?\s*(.*)$", line)
        if sm:
            current = {"name": sm.group(1).strip(), "detail": ""}
            sections.append(current)
            continue
        if current is None:
            continue
        dm = re.match(r"^\[(PASS|FAIL)\]\s*(.*)$", line)
        if dm:
            current["detail"] = dm.group(2)          # PASS/FAIL 断言最有信息量
            continue
        im = re.match(r"^\[INFO\]\s*(.*)$", line)
        if im and "API request returned" not in im.group(1) \
           and "ssl_capture_rate" not in im.group(1) \
           and "ssl_content_recovery" not in im.group(1):
            current["detail"] = im.group(1)          # 记录非进度/非指标的 INFO（如事件统计）
            continue

    for s in sections:
        if s["name"] and s["name"] not in result.sections:
            result.sections.append(s["name"])

    # ── 第二遍：末尾结果清单行，按名称匹配章节并附详情 ──
    def _match_section(name: str) -> str:
        low = name.lower()
        for s in sections:
            if low in s["name"].lower():
                return s["name"]
        return ""

    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        rm = re.match(r"^\s{2,}(PASS|FAIL)\s+(.+)$", line)
        if not rm:
            continue
        status, name = rm.group(1), rm.group(2).strip()
        sec = _match_section(name)
        detail = ""
        for s in sections:
            if s["name"] == sec:
                detail = s.get("detail", "")
                break
        result.cases.append(_new_case(sec, name, status, detail))

    m = re.search(r"Results:\s*(\d+)/(\d+)\s+passed", text, re.IGNORECASE)
    if m:
        result.summary = {
            "passed": int(m.group(1)),
            "failed": int(m.group(2)) - int(m.group(1)),
            "skipped": 0,
            "total": int(m.group(2)),
        }

    # ── SSL 捕获指标解析（测试输出 ssl_capture_rate=... captured_bytes=... expected_bytes=...）──
    metrics = result.metrics
    rates = re.findall(r"ssl_capture_rate=([0-9.]+)\s+captured_bytes=(\d+)\s+expected_bytes=(\d+)", text)
    if rates:
        best = max(rates, key=lambda x: float(x[0]))
        metrics["ssl_capture_rate_pct"] = float(best[0])
        metrics["captured_bytes"] = int(best[1])
        metrics["expected_bytes"] = int(best[2])
    recovs = re.findall(r"ssl_content_recovery=([0-9.]+)", text)
    if recovs:
        metrics["content_recovery_pct"] = float(max(recovs, key=float))
    return result


