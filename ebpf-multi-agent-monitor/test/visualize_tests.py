def _set_section(text: str) -> str:
    return text.strip() if text else ""


def _new_case(section: str, name: str, status: str, detail: str = "") -> Dict:
    return {"section": _set_section(section), "name": name.strip(),
            "status": status, "detail": (detail or "").strip()}


def _strip_ansi(text: Optional[str]) -> Optional[str]:
    """去除 ANSI 颜色码（\x1b[...m），使带色输出也能被解析。"""
    if not text:
        return text
    return re.sub(r"\x1b\[[0-9;]*m", "", text)


def _read_log(path: str) -> Optional[str]:
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return _strip_ansi(f.read())


def _mark_run(result: SuiteResult, text: str, source: str) -> SuiteResult:
    result.status = "RUN"
    result.source = source
    if os.path.exists(result.log_path):
        try:
            st = os.stat(result.log_path)
            result.log_size = st.st_size
            result.log_mtime = datetime.datetime.fromtimestamp(
                st.st_mtime).strftime("%Y-%m-%d %H:%M:%S")
        except OSError:
            pass
    return result


def _summary_line_match(text: str) -> Optional[Dict]:
    """Find a `Results: X passed, Y failed, Z total` line."""
    m = re.search(r"Results:\s*(\d+)\s+passed,\s*(\d+)\s+failed(?:,\s*(\d+)\s+total)?",
                  text, re.IGNORECASE)
    if not m:
        return None
    passed = int(m.group(1))
    failed = int(m.group(2))
    total = m.group(3)
    return {"passed": passed, "failed": failed,
            "skipped": 0, "total": int(total) if total else passed + failed}


