def _real_log_dir(option: str) -> str:
    if option:
        return os.path.abspath(option)
    return os.path.join(TEST_DIR, "logs")


def collect(args) -> List[SuiteResult]:
    log_dir = _real_log_dir(args.logs_dir)
    suites = []
    for s in SUITES:
        s.log_dir = log_dir
        s.log_path = os.path.join(log_dir, s.log_name)
        if s.key == "unit" and not args.no_run_unit:
            _run_unit_live(s)
        else:
            _load_from_log(s)
        s._audit()
        suites.append(s)
    return suites


def _run_unit_live(s: SuiteResult) -> None:
    bin_path = os.path.join(TEST_DIR, "test_unit")
    if not os.path.exists(bin_path):
        s.status = "NOT_RUN"
        s.status_detail = "缺少二进制 test_unit（请先 make -C test）"
        return
    try:
        proc = subprocess.run([bin_path], cwd=TEST_DIR, capture_output=True,
                              text=True, timeout=180)
        text = _strip_ansi(proc.stdout + proc.stderr)
    except Exception as exc:  # pragma: no cover
        s.status = "NOT_RUN"
        s.status_detail = f"单元测试执行失败: {exc}"
        return

    try:
        os.makedirs(os.path.dirname(s.log_path), exist_ok=True)
        with open(s.log_path, "w", encoding="utf-8") as f:
            f.write(text)
    except OSError:
        pass

    _mark_run(s, text, "live")
    if not text.strip():
        s.parse_warning = "单元测试输出为空"
        return
    PARSERS["unit"](text, s)


def _load_from_log(s: SuiteResult) -> None:
    text = _read_log(s.log_path)
    if text is None:
        s.status = "NOT_RUN"
        s.status_detail = f"缺少日志 {s.log_name}（需要 root，请手动运行后保存到 logs/）"
        return
    _mark_run(s, text, "log")
    if not text.strip():
        s.parse_warning = "日志文件为空"
        return
    PARSERS[s.key](text, s)
    if not s.cases and not s.summary and not s.metrics:
        s.parse_warning = "未能从日志中解析出任何测试结果（格式可能不兼容）"


