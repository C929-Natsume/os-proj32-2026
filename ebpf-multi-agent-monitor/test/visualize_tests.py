def _fmt_file_size(n: int) -> str:
    if n >= 1024 * 1024:
        return f"{n / 1024 / 1024:.2f} MB"
    if n >= 1024:
        return f"{n / 1024:.1f} KB"
    return f"{n} B"


def _status_badge(s: SuiteResult) -> str:
    if s.status == "RUN":
        return '<span class="badge b-run">运行</span>'
    return '<span class="badge b-notrun">未运行</span>'


def _integrity_badge(s: SuiteResult) -> str:
    return BADGE.get(s.integrity.get("badge"), BADGE["unverified"])


def _status_cell(case: Dict) -> str:
    color = STATUS_COLORS.get(case["status"], STATUS_COLORS["UNKNOWN"])
    return f'<span class="case-status" style="color:{color};font-weight:bold">{case["status"]}</span>'


