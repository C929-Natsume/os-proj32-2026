def _fig_b64(fig) -> str:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def chart_overview(suites: List[SuiteResult]) -> str:
    """Grouped stacked bars: pass/fail/skip per suite + NOT_RUN, with pass-rate."""
    names = [s.name for s in suites]
    x = range(len(names))
    pass_c, fail_c, skip_c, notrun_c = [], [], [], []
    rates = []
    for s in suites:
        pc = s.parsed_counts
        pass_c.append(pc["PASS"])
        fail_c.append(pc["FAIL"])
        skip_c.append(pc["SKIP"])
        notrun_c.append(s.parsed_total if s.status == "RUN" else 0)
        tot = pc["PASS"] + pc["FAIL"]
        rates.append(pc["PASS"] / tot * 100 if tot else (100.0 if s.status == "RUN" else 0.0))

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(11, 8), dpi=150,
                                   gridspec_kw={"height_ratios": [2.6, 1]})

    b1 = ax1.bar(x, pass_c, 0.6, color=STATUS_COLORS["PASS"], label="PASS")
    b2 = ax1.bar(x, fail_c, 0.6, bottom=pass_c, color=STATUS_COLORS["FAIL"], label="FAIL")
    b3 = ax1.bar(x, skip_c, 0.6, bottom=[p + f for p, f in zip(pass_c, fail_c)],
                 color=STATUS_COLORS["SKIP"], label="SKIP")
    for i, s in enumerate(suites):
        if s.status == "NOT_RUN":
            ax1.bar(i, 1, 0.6, color=STATUS_COLORS["NOT_RUN"],
                    hatch="//", edgecolor="#bdc3c7", label="NOT RUN" if i == 0 else None)
