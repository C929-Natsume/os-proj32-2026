def chart_overall_donut(suites: List[SuiteResult]) -> str:
    """Overall donut of PASS / FAIL / SKIP / NOT RUN."""
    counts = {"PASS": 0, "FAIL": 0, "SKIP": 0, "NOT RUN": 0}
    for s in suites:
        pc = s.parsed_counts
        counts["PASS"] += pc["PASS"]
        counts["FAIL"] += pc["FAIL"]
        counts["SKIP"] += pc["SKIP"]
        if s.status == "NOT_RUN":
            counts["NOT RUN"] += 1
    labels = [k for k, v in counts.items() if v > 0]
    values = [counts[k] for k in labels]
    colors = [STATUS_COLORS[l] if l in STATUS_COLORS else STATUS_COLORS["NOT_RUN"]
              for l in labels]
    total_verdict = counts["PASS"] + counts["FAIL"]
    rate = counts["PASS"] / total_verdict * 100 if total_verdict else 0.0

    fig, ax = plt.subplots(figsize=(6.5, 6), dpi=150)
    wedges, _ = ax.pie(values, labels=labels, colors=colors, startangle=90,
                       counterclock=False, wedgeprops=dict(width=0.38, edgecolor="white"))
    ax.text(0, 0.08, f"{rate:.1f}%", ha="center", va="center", fontsize=24,
            fontweight="bold", color=COLORS["dark"])
    ax.text(0, -0.14, "用例通过率", ha="center", va="center", fontsize=10,
            color=COLORS["gray"])
    ax.set_title("总体用例状态分布 Overall Case Distribution", fontweight="bold")
    fig.tight_layout()
    return _fig_b64(fig)


def chart_integrity(suites: List[SuiteResult]) -> str:
    """Data integrity audit: summary-line total vs parsed per-case total."""
    run_suites = [s for s in suites if s.status == "RUN"]
    if not run_suites:
        return None
    names = [s.name for s in run_suites]
    x = range(len(names))
    parsed = [s.parsed_total for s in run_suites]
    expected = [s.summary_total() for s in run_suites]
    consistent = [s.integrity.get("consistent") for s in run_suites]

    fig, ax = plt.subplots(figsize=(10, 5.5), dpi=150)
    ax.bar(x, parsed, 0.45, color=COLORS["primary"], label="解析到的用例数 Parsed")
    exp_plot = []
    for i, e in enumerate(expected):
        if e is None:
            exp_plot.append(0)
        else:
            exp_plot.append(e)
    ax.plot(list(x), exp_plot, "D", color=COLORS["danger"], markersize=8,
            label="汇总行计数 Summary line")
    for i, (p, e) in enumerate(zip(parsed, expected)):
        tag = "✓" if consistent[i] is True else ("≠" if consistent[i] is False else "?")
        color = STATUS_COLORS["PASS"] if consistent[i] is True else (
            STATUS_COLORS["FAIL"] if consistent[i] is False else STATUS_COLORS["SKIP"])
        ax.annotate(f"{tag}  {p}" + (f" / {e}" if e is not None else ""),
                    (i, p + max(parsed) * 0.03), ha="center", fontsize=9,
                    color=color, fontweight="bold")
    ax.set_xticks(list(x))
    ax.set_xticklabels(names, fontsize=8, rotation=15, ha="right")
    ax.set_ylabel("用例数 Case count")
    ax.set_title("数据完整性审计：逐用例解析 vs 汇总行计数（✓ 一致 / ≠ 偏差 / ? 无汇总行）",
                 fontweight="bold")
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    ax.set_ylim(0, max(parsed + [e or 0 for e in expected if e] + [1]) * 1.22)
    fig.tight_layout()
    return _fig_b64(fig)


def chart_section_stacked(suites: List[SuiteResult]) -> Optional[str]:
    """Per-section stacked bars for suites that have sections."""
    target = None
    for s in suites:
        if s.status == "RUN" and len(s.sections) > 1:
            target = s
            break
    if target is None:
        return None

    sections = list(target.sections)
    pass_by, fail_by, skip_by = [], [], []
    for sec in sections:
        p = f = k = 0
        for c in target.cases:
            if c["section"] != sec:
                continue
            if c["status"] == "PASS":
                p += 1
            elif c["status"] == "FAIL":
                f += 1
            elif c["status"] == "SKIP":
                k += 1
        pass_by.append(p)
        fail_by.append(f)
        skip_by.append(k)

    x = range(len(sections))
    fig, ax = plt.subplots(figsize=(11, 6), dpi=150)
    ax.bar(x, pass_by, 0.6, color=STATUS_COLORS["PASS"], label="PASS")
    ax.bar(x, fail_by, 0.6, bottom=pass_by, color=STATUS_COLORS["FAIL"], label="FAIL")
    ax.bar(x, skip_by, 0.6, bottom=[p + f for p, f in zip(pass_by, fail_by)],
           color=STATUS_COLORS["SKIP"], label="SKIP")
    for i, p in enumerate(pass_by):
        if p:
            ax.text(i, p / 2, str(p), ha="center", va="center", fontsize=8,
                    color="white", fontweight="bold")
    for i, (f, base) in enumerate(zip(fail_by, pass_by)):
        if f:
            ax.text(i, base + f / 2, str(f), ha="center", va="center", fontsize=8,
                    color="white", fontweight="bold")
    ax.set_xticks(list(x))
    ax.set_xticklabels([f"[{i + 1}] {s}" for i, s in enumerate(sections)],
                       fontsize=7, rotation=20, ha="right")
    ax.set_ylabel("用例数 Case count")
    ax.set_title(f"{target.name} — 各章节用例分布 Section Breakdown", fontweight="bold")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(axis="y", alpha=0.3)
    ax.set_ylim(0, max([p + f + k for p, f, k in zip(pass_by, fail_by, skip_by)] + [1]) * 1.15)
    fig.tight_layout()
    return _fig_b64(fig)


def chart_perf_metrics(suites: List[SuiteResult]) -> Optional[str]:
    perf = next((s for s in suites if s.key == "perf" and s.status == "RUN"), None)
    if perf is None or not perf.metrics:
        return None
    m = perf.metrics

    labels = ["baseline 基线", "fast-path 快速路径", "full-capture 全量捕获"]
    times = []
    for key in ("phase_baseline_s", "phase_fastpath_s", "phase_fullcapture_s"):
        v = m.get(key)
        if v and v != "N/A":
            try:
                times.append(float(v))
            except ValueError:
                times.append(None)
        else:
            times.append(None)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 5), dpi=150)

    valid = [(i, t) for i, t in enumerate(times) if t is not None]
    if valid:
        ax1.bar([l for l, _ in valid], [t for _, t in valid],
                color=[COLORS["baseline"], COLORS["fastpath"], COLORS["fullcapture"]][:len(valid)],
                width=0.5)
        for l, t in valid:
            ax1.text(l, t + max(t for _, t in valid) * 0.02, f"{t:.2f}s",
                     ha="center", fontsize=9)
    ax1.set_xticks([l for l, _ in valid] if valid else [])
    ax1.set_xticklabels([labels[l] for l, _ in valid] if valid else [],
                        fontsize=8, rotation=15, ha="right")
    ax1.set_ylabel("耗时 Workload time (s)")
    ax1.set_title("阶段耗时对比 Phase Timing", fontweight="bold")
    ax1.grid(axis="y", alpha=0.3)

    oh = m.get("overhead_pct")
    rate = m.get("capture_rate_pct")
    drops = m.get("drop_counter")
    rows = []
    if oh:
        rows.append(("平均开销 Overhead", f"{oh}%"))
    if rate:
        rows.append(("管道捕获率 Capture rate", f"{rate}%"))
    if drops:
        rows.append(("drop_counter 丢包计数", str(drops)))
    if m.get("overhead_basis"):
        rows.append(("开销基准 Basis", str(m["overhead_basis"])))
    ax2.axis("off")
    if rows:
        tb = ax2.table(cellText=rows, loc="center", cellLoc="center", colWidths=[0.55, 0.3])
        tb.auto_set_font_size(False)
        tb.set_fontsize(10)
        tb.scale(1.1, 1.8)
        for (row, col), cell in tb.get_celld().items():
            if col == 0:
                cell.set_facecolor(COLORS["light_gray"])
    ax2.set_title("性能关键指标 Key Metrics", fontweight="bold", pad=12)

    fig.tight_layout()
    return _fig_b64(fig)


